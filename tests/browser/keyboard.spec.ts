import { expect, test } from '@playwright/test'

test('desktop coordinate dialog restores its external keyboard opener', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /Use nearest usable cell,/ }).click()
  await expect(page.getByRole('button', { name: 'Start simulation', exact: true })).toBeEnabled()
  const opener = page.getByRole('button', { name: 'Enter coordinates', exact: true }).first()
  await opener.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Enter habitat coordinates' })
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(opener).toBeFocused()
})

test('tablet coordinate entry and planner sheet return focus to the surviving launcher', async ({ page }) => {
  await page.setViewportSize({ width: 768, height: 1024 })
  await page.goto('/')
  await page.getByRole('button', { name: /Use nearest usable cell,/ }).click()
  await expect(page.getByRole('button', { name: 'Start simulation', exact: true })).toBeEnabled()
  const launcher = page.getByRole('button', { name: 'Mission planner', exact: true })
  await launcher.focus()
  await page.keyboard.press('Enter')
  const sheet = page.getByRole('dialog', { name: 'Mission planner', exact: true })
  const details = sheet.locator('summary').filter({ hasText: 'Planning details' })
  await details.focus()
  await page.keyboard.press('Enter')
  const source = sheet.getByRole('button', { name: /Show source:/ }).first()
  await source.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog').last()).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(sheet).toBeVisible()
  await expect(source).toBeFocused()
  const entry = sheet.getByRole('button', { name: 'Enter coordinates', exact: true }).first()
  await entry.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Enter habitat coordinates' })
  await expect(dialog).toBeVisible()
  await expect(sheet).not.toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(launcher).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(sheet).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(sheet).not.toBeVisible()
  await expect(launcher).toBeFocused()
})
